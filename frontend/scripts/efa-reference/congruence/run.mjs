import { build } from 'esbuild';
import { mkdtemp, readFile, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import { currentPackageBuild } from '../../ci/package-build.mjs';
const packageHashes = currentPackageBuild();
const temporary = await mkdtemp(join(tmpdir(), 'efa-congruence-'));
const file = join(temporary, 'check.mjs');
const bundle = await build({ entryPoints: [process.env.CONGRUENCE_ENTRY ?? 'scripts/efa-reference/congruence/check.ts'], outfile: file, bundle: true, platform: 'node', format: 'esm', metafile: true });
const hashes = { ...packageHashes };
for (const input of Object.keys(bundle.metafile.inputs)) hashes[input] = createHash('sha256').update(await readFile(input)).digest('hex');
const report = process.env.CONGRUENCE_OUTPUT ?? 'scripts/efa-reference/congruence/numerical-report.json';
await mkdir(dirname(report), { recursive: true });
await writeFile(`${report}.inputs.json`, JSON.stringify({ bundle: file, bundleSha256: createHash('sha256').update(await readFile(file)).digest('hex'), sourceHashes: hashes }, null, 2) + '\n');
const child = spawn(process.execPath, [file], { stdio: 'inherit', env: process.env });
const exitCode = await new Promise(resolve => child.on('exit', resolve));
const drift = [];
for (const [input, hash] of Object.entries(hashes)) if (createHash('sha256').update(await readFile(input)).digest('hex') !== hash) drift.push(input);
await writeFile(`${report}.drift.json`, JSON.stringify({ changedAfterBundle: drift }, null, 2) + '\n');
process.exitCode = drift.length ? 1 : exitCode ?? 1;
